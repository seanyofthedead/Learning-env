#!/usr/bin/env python3
"""Regenerate app/cache.json by calling a real model (needs an API key and network).

  export ANTHROPIC_API_KEY=...        # or OPENAI_API_KEY=... and DEMO_MODEL=...
  python3 scripts/regenerate_cache.py
  python3 scripts/preflight.py        # must print PASS before you present

What it sends (same as live mode, scripts/live_server.py):
  Demo 1: each of the five ladder prompts + the report as text (the CSV export of the
          same data that is in the .xlsx/.docx).
  Demo 2: the Demo 2 prompt + the text extracted from the clean .docx, then from the
          injected .docx. Both are sent under the neutral name "demo_report.docx" so the
          safety label in the injected file's name does not tip off the model.

Afterwards it rewrites app/cache.json (mode "model-generated", with the model ID and
temperature actually used), re-embeds it in app/index.html, and appends a dated line
to ASSUMPTIONS.md. If preflight then fails (for example the model refused to follow the
hidden instruction), you can run again, present the result honestly, or restore the
representative cache with:  python3 scripts/build_cache.py
"""
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_cache  # noqa: E402
import model_client  # noqa: E402
import office_text  # noqa: E402

ROOT = build_cache.ROOT
REPORT_CSV = os.path.join(ROOT, "data", "fy26_q3_execution_report.csv")
CLEAN_DOCX = os.path.join(ROOT, "demo2", "demo_report.docx")
INJECTED_DOCX = os.path.join(ROOT, "demo2", "INJECTED_demo_report_DO_NOT_USE.docx")
NEUTRAL_NAME = "demo_report.docx"


def request_for(demo, key):
    """(prompt, file_name, file_text) for one cached output. Shared with live_server."""
    if demo == "demo1":
        src = build_cache.build_demo1({f"demo1_{s}": "" for s in
                                       ("weak", "role", "task", "context", "output")})
        stage = next(s for s in src["stages"] if s["id"] == key)
        return stage["prompt"], "fy26_q3_execution_report.csv", office_text.csv_text(REPORT_CSV)
    if demo == "demo2" and key in ("clean", "injected"):
        path = CLEAN_DOCX if key == "clean" else INJECTED_DOCX
        return build_cache.DEMO2_PROMPT, NEUTRAL_NAME, office_text.docx_text(path)
    raise KeyError(f"{demo}/{key}")


def main():
    if model_client.provider() is None:
        sys.exit("No ANTHROPIC_API_KEY or OPENAI_API_KEY set. Nothing regenerated; "
                 "the representative cache is unchanged.")
    jobs = [("demo1", s) for s in ("weak", "role", "task", "context", "output")]
    jobs += [("demo2", "clean"), ("demo2", "injected")]
    outputs, models, temps = {}, set(), set()
    for demo, key in jobs:
        prompt, name, text = request_for(demo, key)
        print(f"  {demo}/{key} ...", end="", flush=True)
        r = model_client.generate(prompt, name, text)
        outputs[f"{demo}_{key}"] = r["markdown"]
        models.add(r["model"])
        temps.add(r["temperature"])
        print(f" {r['latency_ms']} ms")
    model = ", ".join(sorted(models))
    temperature = 0 if temps == {0} else None
    today = datetime.date.today().isoformat()
    note = (f"Generated by {model} on {today}"
            + (" at temperature 0." if temperature == 0 else
               " at the model's default sampling (it does not accept temperature 0)."))
    build_cache.build(outputs, {"mode": "model-generated", "model": model,
                                "temperature": temperature, "generated_at": today, "note": note})
    with open(os.path.join(ROOT, "ASSUMPTIONS.md"), "a", encoding="utf-8") as f:
        f.write(f"\n- Cache regenerated {today}: {note} (scripts/regenerate_cache.py)\n")
    print("Wrote app/cache.json. " + note)
    print("Now run: python3 scripts/preflight.py")


if __name__ == "__main__":
    main()
